#!/usr/bin/env node
/**
 * Generates third-party licence notices for software that ships inside the built app:
 *   - the production dependency tree (npm ls --omit=dev --all), minus type-only packages;
 *   - the Workbox modules that vite-plugin-pwa bundles into the service worker.
 * Writes src/about/notices.json (shown in the About screen) and docs/THIRD_PARTY_NOTICES.md (full licence texts).
 *
 *   node scripts/gen_notices.mjs
 *
 * Run it again whenever dependencies change. Data licensing (OpenStreetMap, ODbL) is documented separately in docs/licensing.md.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const NOT_SHIPPED = (n) => n.startsWith('@types/') || n === 'csstype' || n === 'typescript';
const WORKBOX = ['workbox-core', 'workbox-precaching', 'workbox-routing', 'workbox-strategies', 'workbox-window'];

let out;
try { out = execFileSync('npm', ['ls', '--omit=dev', '--all', '--json'], { cwd: root, encoding: 'utf8', maxBuffer: 1 << 28 }); }
catch (e) { out = e.stdout; } // npm exits non-zero on peer warnings but still prints the tree
const names = new Set(WORKBOX);
(function walk(d) {
  for (const [n, v] of Object.entries(d.dependencies ?? {})) { if (!NOT_SHIPPED(n)) names.add(n); walk(v); }
})(JSON.parse(out));

function licenseText(dir) {
  const f = readdirSync(dir).find((x) => /^(licen[sc]e|copying)(\.|$)/i.test(x));
  return f ? readFileSync(join(dir, f), 'utf8').trim() : null;
}
const spdx = (pkg) => (typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? (pkg.licenses?.map((l) => l.type).join(' OR ') ?? 'UNKNOWN'));

const rows = [...names].sort().map((name) => {
  const dir = join(root, 'node_modules', name);
  if (!existsSync(join(dir, 'package.json'))) throw new Error(`${name} is in the dependency tree but not installed; run npm ci first`);
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  return { name, version: pkg.version, license: spdx(pkg), text: licenseText(dir) };
});

const unknown = rows.filter((r) => r.license === 'UNKNOWN');
if (unknown.length) throw new Error(`no licence declared for: ${unknown.map((r) => r.name).join(', ')}`);

mkdirSync(join(root, 'src', 'about'), { recursive: true });
writeFileSync(join(root, 'src', 'about', 'notices.json'),
  JSON.stringify(rows.map(({ name, version, license }) => ({ name, version, license })), null, 2) + '\n');

const md = [
  '# Third-party notices',
  '',
  "D'Maps ships with the open-source software below. Generated by `scripts/gen_notices.mjs`; do not edit by hand.",
  'Map data is covered separately: © OpenStreetMap contributors, ODbL 1.0 (see `docs/licensing.md`).',
  '',
  '| Package | Version | Licence |',
  '|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
  '',
  ...rows.flatMap((r) => ['---', '', `## ${r.name} ${r.version} (${r.license})`, '', r.text ? '```text\n' + r.text + '\n```' : '_No licence file in the package; licence declared in package.json: ' + r.license + '._', '']),
].join('\n');
writeFileSync(join(root, 'docs', 'THIRD_PARTY_NOTICES.md'), md);
console.log(`${rows.length} packages -> src/about/notices.json, docs/THIRD_PARTY_NOTICES.md`);
const nolicfile = rows.filter((r) => !r.text).map((r) => r.name);
if (nolicfile.length) console.log(`note: no LICENSE file shipped by: ${nolicfile.join(', ')}`);
