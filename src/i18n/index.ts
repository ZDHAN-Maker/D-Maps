const LANG_KEY = 'dmaps.lang';

/** Reads the saved language; storage can throw (private mode, blocked data) so it is always guarded. */
export function savedLanguage(): Lang {
  try {
    const v = localStorage.getItem(LANG_KEY);
    if (v === 'id' || v === 'en') return v;
  } catch { /* storage unavailable: fall through to default */ }
  return 'id';
}

export function saveLanguage(lang: Lang): void {
  try { localStorage.setItem(LANG_KEY, lang); } catch { /* preference simply won't persist */ }
}

