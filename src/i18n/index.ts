export async function initI18n(lang: Lang = savedLanguage()) {
  await i18next.use(initReactI18next).init({
    lng: lang,
    fallbackLng: 'id',
    resources: { id: { translation: id }, en: { translation: en } },
    interpolation: { escapeValue: false }, // React already escapes
    returnNull: false,
  });
  return i18next;
}

